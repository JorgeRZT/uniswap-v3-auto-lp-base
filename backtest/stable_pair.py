#!/usr/bin/env python3
"""Stable-pair LP (USDC/USDT, Uniswap V3 0.01 % pool on Base) with the same engine -> backtest/RESULTS_STABLE.md

    SYMBOL=USDCUSDT python3 backtest/fetch_1m.py      # once
    POOL_ADDR=0xD56da2B74bA826f19015E6B7Dd9Dae1903E85DA1 python3 backtest/pool_volume.py 168   # refresh the volume
    python3 backtest/stable_pair.py

Pool facts measured on-chain on 2026-11-01 (Base): 0.01 % pool 0xD56d...5DA1, TVL ~ 226 k$ (122 k USDC + 104 k USDT),
active liquidity 1.468e14 raw (= 1.468e8 in human units), 7-day volume 0.50 M$/day.
"""
import pathlib, statistics, sys
HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
from backtest import Params, load, run

EURUSD = 1.1233
LIQ = 1.468e14 / 1e6
VOL = 0.50e6
d = load(HERE / "data" / "usdcusdt_1m.csv"); ts, o, h, l, c, qv = d
RANGES = (0.0002, 0.0005, 0.001, 0.002, 0.005, 0.01)
CAPS = (100, 250, 500, 1000, 1500, 2000, 2500)
S = dict(fee=0.0001, active_liq_h=LIQ, twap_s=300, cooldown_s=300, max_per_day=50)

def md(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---:" if i else ":---" for i in range(len(header))) + "|\n"
    return s + "".join("| " + " | ".join(str(x) for x in r) + " |\n" for r in rows)

out = []; A = out.append
A("# Backtest — stable pair (USDC/USDT, 0.01 % pool on Base)\n")
A("_Generated by `backtest/stable_pair.py`. The contract in this repository does NOT support this pair (see section 5)._\n")
A(f"- **Prices:** Binance USDCUSDT 1-minute candles, 2025-11-01 → 2026-11-01 ({len(c):,} candles). Min {min(l):.4f}, max {max(h):.4f}. **No depeg in the sample.**")
A("- **Pool (on-chain, 2026-11-01):** USDC/USDT 0.01 % = `0xD56da2B74bA826f19015E6B7Dd9Dae1903E85DA1`, TVL ≈ 226 k$, 7-day volume **0.50 M$/day**, active liquidity 1.47e8 (human units). The 0.05 % stable pool is far smaller (≈ 11 k$ TVL).")
A("- Same engine and assumptions as the other backtests: TWAP-centred range, rebalance at 85 % of the way to a boundary, swap fee 0.01 % + 0.02 $ per tx, fees reserved, HODL benchmark. Relaxed limits (cooldown 5 min, ≤50/day, TWAP 5 min).\n")

A("## 1. How often does the peg leave a given range?\n")
rows = [[f"±{r*100:g} %", f"{sum(1 for x in c if abs(x-1) > r)/len(c)*100:.2f} %"] for r in (0.0002, 0.0005, 0.001, 0.002, 0.005, 0.01, 0.02)]
A(md(["range around 1.0000", "share of minutes outside it"], rows))

A("## 2. Result vs HODL by range and capital (full year, % — pool volume 0.50 M$/day)\n")
rows = []
for r in RANGES:
    row = [f"±{r*100:g} %"]; ref = None
    for cap in CAPS:
        res = run(d, Params(capital=cap * EURUSD, range_pct=r, pool_daily_volume=VOL, **S)); row.append(f"{res['vs_hodl_pct']:+.1f}")
        if cap == 1000: ref = res
    row += [ref["rebalances"], f"{ref['fees']/EURUSD:.0f} €", f"{ref['in_range_pct']:.0f} %"]
    rows.append(row)
A(md(["range"] + [f"{c_} €" for c_ in CAPS] + ["rebalances/yr", "fees earned (1000 €)", "time in range"], rows))
A("_Rows below ±0.05 % are not reliable: Binance quotes in steps of 0.0001 (1 bp), so a ±0.02 % (2 bp) range sees an artificially jumpy price._\n")

A("## 3. Sensitivity to the pool's daily volume (1000 €, ±0.05 % and ±0.2 %)\n")
rows = []
for r in (0.0005, 0.002):
    row = [f"±{r*100:g} %"]
    for v in (0.1e6, 0.25e6, 0.5e6, 1e6, 2e6):
        row.append(f"{run(d, Params(capital=1000*EURUSD, range_pct=r, pool_daily_volume=v, **S))['vs_hodl_pct']:+.1f}")
    rows.append(row)
A(md(["range", "0.1 M$/day", "0.25 M$/day", "0.5 M$/day (measured)", "1 M$/day", "2 M$/day"], rows))

A("## 3b. Sensitivity to competition (more concentrated liquidity from other LPs) and volume — ±0.05 %, 1000 €\n")
A("`x2` = other LPs hold twice today's active liquidity near the price. Yield compresses quickly: attractive stable-pair yields attract capital.\n")
rows = []
for v in (0.1e6, 0.25e6, 0.5e6, 1e6):
    row = [f"{v/1e6:g} M$/day"]
    for m in (1, 2, 4, 8):
        row.append(f"{run(d, Params(capital=1000*EURUSD, range_pct=0.0005, pool_daily_volume=v, **{**S, 'active_liq_h': LIQ*m}))['vs_hodl_pct']:+.1f}")
    rows.append(row)
A(md(["pool volume", "competitors x1 (today)", "x2", "x4", "x8"], rows))

A("## 4. Why this looks so different from ETH/USDC — and why not to trust it blindly\n")
A("""1. **Almost no price-movement loss.** USDC and USDT stay within ±0.1 % of 1.0000 about 89 % of the time, so concentrating liquidity costs
   little; fees are not eaten by LVR. That is the whole difference with ETH/USDC.
2. **No depeg in the sample.** The tail risk of stable pairs is a depeg (a stablecoin falling well below 1.00): the position ends up
   100 % in the weaker coin, and rebalancing then locks the loss. If the weaker coin falls X %, the position loses about X % of capital
   (about 0.4-0.5 years of the ±0.05 % fees for a −10…−12 % depeg, and several years for a collapse). **This sample cannot show that risk.**
3. **Tiny pool, tiny capacity.** 0.50 M$/day and ≈ 226 k$ TVL. A few thousand euros fit; much more would dilute your own fee share
   (the table already accounts for your share of today's liquidity, not for new LPs joining because the yield looks attractive).
4. **Fee income depends on volume** (section 3), measured over only 7 days.
5. **Price source:** Binance USDCUSDT as a proxy for the Base pool; the pool price sits ~1 bp away from 1.0000 and has its own noise.
6. **Counter-party risks not in the numbers:** issuer risk (freeze/blacklist, redemption), bridge risk for the Base-native USDT, smart-contract risk.\n""")

A("## 5. What it would take to run this with the current code\n")
A("""The contract is hard-wired to WETH/USDC (`weth`/`usdc` immutables, fair value via a WETH→USDC quote, fee tiers 500/3000 only, range ≥ ±2 %,
tick spacing assumptions, no peg guard). A stable-pair version would need: arbitrary token pair with 1:1 valuation, fee tier 100 and
spacing 1, ranges of a few ticks, a **peg-deviation circuit breaker** (close and hold if the pair deviates more than X from 1.00),
and its own tests. It is a separate scope and needs your decision.""")
(HERE / "RESULTS_STABLE.md").write_text("\n".join(out) + "\n")
print("wrote backtest/RESULTS_STABLE.md")
