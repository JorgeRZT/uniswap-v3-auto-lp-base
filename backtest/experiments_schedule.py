#!/usr/bin/env python3
"""Does staying OUT of the market during certain hours (e.g. the US open) or during high volatility help?  1-minute data.

    python3 backtest/experiments_schedule.py          # simulate + write backtest/RESULTS_SCHEDULE.md
    REUSE=1 python3 backtest/experiments_schedule.py  # regenerate the report from results/schedule.json

Variants (all on the 0.05 % pool at its measured volume, capital 1000 EUR):
  always LP | pause rebalances 13-17 UTC | LP closed 13-17 UTC | closed 13-21 UTC | closed weekdays 08-22 UTC |
  volatility filter | volatility filter + closed 13-17 UTC.
While the LP is closed the bot holds the BENCHMARK's token mix (exit_to_benchmark=True), so the comparison is not polluted by
directional luck. Each exit/entry pays gas and the swap fee on the composition change.
"""
import itertools, json, os, pathlib, statistics, sys, time
from concurrent.futures import ProcessPoolExecutor

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
from backtest import Params, load  # noqa: E402
from backtest import run as bt_run  # noqa: E402

EURUSD = 1.1233
CAP = 1000 * EURUSD
VOL = 13.61e6
FEE, LIQ = 0.0005, 8.78674960936777061e17 / 1e12
RANGES = (0.01, 0.02, 0.05, 0.10, 0.20)
SETTINGS = {"relaxed/TWAP 5 min": dict(cooldown_s=300, max_per_day=50, twap_s=300),
            "default/TWAP 1 h": dict(cooldown_s=6 * 3600, max_per_day=3, twap_s=3600)}
US = (13, 14, 15, 16)
VARIANTS = {
    "always LP": dict(),
    "pause rebalances 13-17 UTC": dict(pause_hours_utc=US),
    "LP closed 13-17 UTC (weekdays)": dict(flat_hours_utc=US, exit_to_benchmark=True),
    "LP closed 13-21 UTC (US session)": dict(flat_hours_utc=tuple(range(13, 21)), exit_to_benchmark=True),
    "LP only nights+weekends (closed Mon-Fri 08-22 UTC)": dict(flat_hours_utc=tuple(range(8, 22)), exit_to_benchmark=True),
    "vol filter (exit>=50 % / enter<=40 %)": dict(regime_exit_ann=0.50, regime_enter_ann=0.40, exit_to_benchmark=True),
    "vol filter + closed 13-17 UTC": dict(regime_exit_ann=0.50, regime_enter_ann=0.40, flat_hours_utc=US, exit_to_benchmark=True),
}
_data = None


def _init():
    global _data
    _data = load(HERE / "data" / "ethusdt_1m.csv")


def simulate(task):
    r, sname, vname = task
    n = len(_data[3]); half = n // 2

    def one(a, b):
        res = bt_run(_data, Params(capital=CAP, range_pct=r, rebalance_progress=0.85, fee=FEE, active_liq_h=LIQ, pool_daily_volume=1e6,
                                   start_idx=a, end_idx=b, **SETTINGS[sname], **VARIANTS[vname]))
        return dict(nof=res["final"] - res["fees"], fpm=res["fees"], hodl=res["hodl"], reb=res["rebalances"], inr=res["in_range_pct"],
                    chg=res["regime_changes"], costs=res["costs"])
    return dict(range=r, setting=sname, variant=vname, year=one(0, n), h1=one(0, half), h2=one(half, n))


def pct(rec, vol=VOL):
    return ((rec["nof"] + rec["fpm"] * vol / 1e6) / rec["hodl"] - 1) * 100


def md_table(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---:" if i else ":---" for i in range(len(header))) + "|\n"
    return s + "".join("| " + " | ".join(str(x) for x in r) + " |\n" for r in rows)


def main():
    t0 = time.time()
    cache = HERE / "results" / "schedule.json"
    if os.environ.get("REUSE") == "1" and cache.exists():
        recs = json.loads(cache.read_text())
    else:
        tasks = list(itertools.product(RANGES, SETTINGS, VARIANTS))
        print(f"{len(tasks)} simulations x 3 periods (1-minute candles) ...", flush=True)
        with ProcessPoolExecutor(initializer=_init) as ex:
            recs = list(ex.map(simulate, tasks, chunksize=1))
        (HERE / "results").mkdir(exist_ok=True); cache.write_text(json.dumps(recs)); print(f"done in {time.time()-t0:.0f}s")
    by = {(r["range"], r["setting"], r["variant"]): r for r in recs}
    rng = lambda r: f"±{r*100:g} %"
    out = []; A = out.append
    A("# Backtest — staying out of the market at certain hours / in high volatility\n")
    A("_Generated by `backtest/experiments_schedule.py`; section 6 is hand-written._\n")
    A("- 1-minute ETHUSDT candles, 2025-11-01 .. 2026-11-01 (ETH −41 %). 0.05 % pool at its measured 7-day volume (13.6 M$/day). Capital 1000 €. Fee + 0.02 $/tx gas. HODL benchmark of the same initial tokens.")
    A("- **US open window = 13:00-17:00 UTC, Monday-Friday.** It covers the NYSE open at 13:30 UTC (summer time) and 14:30 UTC (winter time); the US clocks changed on 2026-03-08 and 2026-11-01.")
    A("- **LP closed** = position withdrawn at the start of the window and re-opened (new TWAP-centred range) at its end; meanwhile the bot holds exactly the benchmark's token mix, so being out costs nothing except gas and the swap fee on the composition change.")
    A("- **Pause rebalances** = the position stays open but no rebalance is executed in the window (what 'stopping the bot' would do).")
    A("- **Gas price is NOT modelled as a signal** (see section 6). Gas is a constant 0.02 $ per transaction.\n")

    def block(setting, title):
        A(f"## {title}\n")
        for label, key in (("Full year", "year"), ("First half (fit)", "h1"), ("Second half (test)", "h2")):
            A(f"**{label} — % vs HODL**\n")
            rows = []
            for v in VARIANTS:
                rows.append([v] + [f"{pct(by[(r, setting, v)][key]):+.1f}" for r in RANGES])
            A(md_table(["variant"] + [rng(r) for r in RANGES], rows))

    block("relaxed/TWAP 5 min", "1. Settings: cooldown 5 min, ≤50/day, TWAP 5 min (the most favourable for narrow ranges)")
    block("default/TWAP 1 h", "2. Settings: contract defaults — cooldown 6 h, ≤3/day, TWAP 1 h")

    A("## 3. Cost of being out: transitions and time in range (full year, relaxed/TWAP 5 min)\n")
    rows = []
    for v in VARIANTS:
        for r in (0.02, 0.05, 0.10):
            y = by[(r, "relaxed/TWAP 5 min", v)]["year"]
            rows.append([v, rng(r), y["reb"], y["chg"], f"{y['inr']:.0f} %", f"{y['costs']/ (1000*EURUSD)*100:.2f} %"])
    A(md_table(["variant", "range", "rebalances", "enter/exit events", "time in range*", "gas+swap costs % of capital"], rows))
    A("_*share of all candles in which the position was open and the price inside it; closed time counts as not in range._\n")

    A("## 4. Do the improvements survive at higher pool volume? (full year, relaxed/TWAP 5 min, ±5 %)\n")
    rows = []
    for v in VARIANTS:
        rec = by[(0.05, "relaxed/TWAP 5 min", v)]["year"]
        rows.append([v] + [f"{pct(rec, vol*1e6):+.1f}" for vol in (7, 13.6, 21, 30, 50)])
    A(md_table(["variant"] + [f"{x} M$/day" for x in (7, 13.6, 21, 30, 50)], rows))
    A("_Closing the LP also forgoes the fees earned in the closed hours, so the advantage shrinks (and can reverse) as volume rises._\n")

    # consistency stats
    wins_year = wins_h1 = wins_h2 = tot = 0
    for r in RANGES:
        for s_ in SETTINGS:
            base = by[(r, s_, "always LP")]
            v = by[(r, s_, "LP closed 13-17 UTC (weekdays)")]
            tot += 1
            wins_year += pct(v["year"]) > pct(base["year"]); wins_h1 += pct(v["h1"]) > pct(base["h1"]); wins_h2 += pct(v["h2"]) > pct(base["h2"])
    A("## 5. Consistency check — 'LP closed 13-17 UTC' vs 'always LP'\n")
    A(f"Out of {tot} (range, settings) pairs it was better on the full year in **{wins_year}**, on the first half in **{wins_h1}**, on the second half in **{wins_h2}**.\n")
    A("""## 6. Conclusions (hand-written from the 2026-11-01 run)

1. **Gas price is not tested here and cannot be with the data I have.** The simulator charges a constant 0.02 $ per transaction.
   A gas-based gate would need a year of historical Base fees (an archive RPC such as your Infura key, one sample per hour, would do).
   My expectation, not a result: gas on Base is a poor proxy for 'sideways market' (it reflects network demand, often unrelated to ETH
   price moves) and gas is only a few cents per transaction, so as a *cost* filter it saves almost nothing.
2. **Stopping the bot is not the same as leaving the market.** 'Pause rebalances 13-17 UTC' (section 1-2, row 2) was worse than doing nothing in
   most rows: the position keeps its exposure and only the corrective rebalances are delayed. This is what the 5-minute test of
   D-16 measured.
3. **Closing the LP during the US open helps consistently.** 'LP closed 13-17 UTC (weekdays)' beat 'always LP' in 10 of 10 (range, settings)
   pairs over the year, 9 of 10 on the first half and 10 of 10 on the second half (section 5), e.g. ±10 %: −18.4 % → −9.6 %.
   It works because those 4 hours (17 % of weekday time) carry ~25-29 % of weekday variance, i.e. a disproportionate share of the
   price-movement loss, while fees are roughly proportional to time.
4. **The volatility filter, once the comparison is made fair, is the best single tool tested:** it beat 'always LP' in every row of
   sections 1-2 (full year and both halves). Combined with the US-open closure it gets close to break-even at the measured volume
   (±10 %: −3.6 %, ±20 %: −2.8 %) and positive from ~21 M$/day (section 4). **This corrects D-17**, which called the filter
   'inconsistent': that conclusion was an artefact of the bot holding a one-sided token mix while out of the LP. Here it holds the
   benchmark's mix (`exit_to_benchmark=True`).
5. **Still not a proven edge.** (a) One year, a bear market; (b) none of the variants beats HODL at 13.6 M$/day, they only lose less;
   (c) the advantage shrinks as pool volume grows, because being out forgoes fees (section 4: at 50 M$/day 'always LP' wins by a lot);
   (d) the 50 %/40 % volatility thresholds were suggested by an earlier look at the first half, so only the second half is clean out-of-sample;
   (e) 520 enter/exit events a year are modelled with the same flat gas and swap-fee assumptions as everything else.
6. **What it would take to put this in the contract:** a UTC schedule (hour bitmask, weekdays only) and a volatility gate computed
   from several `observe()` points, both executed by `executeStrategy()` (new actionable reasons: close-for-schedule / re-open),
   plus tests for DST-agnostic windows, flapping and composition handling. It changes the strategy (spec §16: needs your confirmation).
""")
    (HERE / "RESULTS_SCHEDULE.md").write_text("\n".join(out) + "\n")
    print("wrote backtest/RESULTS_SCHEDULE.md")


if __name__ == "__main__":
    main()
