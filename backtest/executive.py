#!/usr/bin/env python3
"""Executive backtest: ranges ±0.5 %..±15 % x capital 100..2500 EUR x {always LP, closed at US open, volatility filter, both}.

    python3 backtest/executive.py             # simulate (1-minute candles) and write backtest/EXECUTIVE_SUMMARY.md
    REUSE=1 python3 backtest/executive.py     # regenerate the report from results/executive.json

Same engine and assumptions as the other sweeps (see backtest/README.md). Pool: 0.05 % tier at its measured 13.6 M$/day.
While the LP is closed the bot holds the benchmark's token mix, so the comparison with HODL is fair.
"""
import itertools, json, os, pathlib, statistics, sys, time
from concurrent.futures import ProcessPoolExecutor

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
from backtest import Params, load  # noqa: E402
from backtest import run as bt_run  # noqa: E402

EURUSD = 1.1233
VOL = 13.61e6
FEE, LIQ = 0.0005, 8.78674960936777061e17 / 1e12
RANGES = (0.005, 0.01, 0.02, 0.03, 0.05, 0.075, 0.10, 0.15)
CAPS = (100, 250, 500, 1000, 1500, 2000, 2500)
REF = 1000
SETTINGS = {"relaxed": dict(cooldown_s=300, max_per_day=50, twap_s=300), "defaults": dict(cooldown_s=6 * 3600, max_per_day=3, twap_s=3600)}
US = (13, 14, 15, 16)
VARIANTS = {
    "A. Always LP": dict(),
    "B. LP closed 13-17 UTC": dict(flat_hours_utc=US, exit_to_benchmark=True),
    "C. Volatility filter": dict(regime_exit_ann=0.50, regime_enter_ann=0.40, exit_to_benchmark=True),
    "D. Filter + closed 13-17 UTC": dict(regime_exit_ann=0.50, regime_enter_ann=0.40, flat_hours_utc=US, exit_to_benchmark=True),
}
_data = None


def _init():
    global _data
    _data = load(HERE / "data" / "ethusdt_1m.csv")


def simulate(task):
    r, sname, vname = task
    n = len(_data[3]); half = n // 2

    def one(cap, a, b):
        res = bt_run(_data, Params(capital=cap * EURUSD, range_pct=r, rebalance_progress=0.85, fee=FEE, active_liq_h=LIQ, pool_daily_volume=1e6,
                                   start_idx=a, end_idx=b, **SETTINGS[sname], **VARIANTS[vname]))
        return dict(nof=res["final"] - res["fees"], fpm=res["fees"], hodl=res["hodl"], reb=res["rebalances"], chg=res["regime_changes"], inr=res["in_range_pct"])

    return dict(range=r, setting=sname, variant=vname, year={str(c): one(c, 0, n) for c in CAPS},
                h1=one(REF, 0, half), h2=one(REF, half, n))


def pct(rec, vol=VOL):
    return ((rec["nof"] + rec["fpm"] * vol / 1e6) / rec["hodl"] - 1) * 100


def eur(rec, vol=VOL):
    return ((rec["nof"] + rec["fpm"] * vol / 1e6) - rec["hodl"]) / EURUSD


def md(header, rows):
    s = "| " + " | ".join(header) + " |\n|" + "|".join("---:" if i else ":---" for i in range(len(header))) + "|\n"
    return s + "".join("| " + " | ".join(str(x) for x in r) + " |\n" for r in rows)


def main():
    t0 = time.time()
    cache = HERE / "results" / "executive.json"
    if os.environ.get("REUSE") == "1" and cache.exists():
        recs = json.loads(cache.read_text())
    else:
        tasks = list(itertools.product(RANGES, SETTINGS, VARIANTS))
        print(f"{len(tasks)} configs x {len(CAPS)} capitals (1-minute candles) ...", flush=True)
        with ProcessPoolExecutor(initializer=_init) as ex:
            recs = list(ex.map(simulate, tasks, chunksize=1))
        (HERE / "results").mkdir(exist_ok=True); cache.write_text(json.dumps(recs)); print(f"done in {time.time()-t0:.0f}s", flush=True)
    by = {(r["range"], r["setting"], r["variant"]): r for r in recs}
    R = lambda r: f"±{r*100:g} %"
    out = []; A = out.append
    A("# Executive summary — LP rebalancing strategy backtest\n")
    A("**Scope:** ETH/USDC, Uniswap V3 0.05 % pool on Base · ranges ±0.5 %…±15 % · initial capital 100…2500 € · 1 year of 1-minute prices "
      "(2025-11-01 → 2026-11-01; ETH −41 %, realised vol ≈ 61 %) · pool volume 13.6 M$/day (measured on-chain) · benchmark: just holding the same tokens (HODL). "
      "All figures are **% vs HODL** (negative = the strategy lost to simply holding). Generated by `backtest/executive.py`; assumptions and limits in `backtest/README.md`.\n")

    # ---- headline numbers
    allv = [(pct(r["year"][str(REF)]), r) for r in recs if r["setting"] == "relaxed"]
    best_by_variant = {v: max(((pct(by[(rg, "relaxed", v)]["year"][str(REF)]), rg) for rg in RANGES)) for v in VARIANTS}
    n_pos = sum(1 for r in recs for c in CAPS if pct(r["year"][str(c)]) > 0)
    n_all = len(recs) * len(CAPS)
    A("## 1. Bottom line\n")
    A(f"- **At today's pool volume (13.6 M$/day) the strategy does not beat holding in any variant**: {n_pos} of {n_all} range × capital × variant × settings combinations were positive.")
    bA, bD = best_by_variant["A. Always LP"], best_by_variant["D. Filter + closed 13-17 UTC"]
    A(f"- **Best plain version (always LP): {bA[0]:+.1f} %** (at {R(bA[1])}). **Best with schedule + volatility filter: {bD[0]:+.1f} %** (at {R(bD[1])}). "
      "For ranges ±5 % and wider, staying out at the US open and in high volatility removes more than half of the loss; for ±0.5…±2 % it removes only ~20-50 %. It does not turn the result positive.")
    A("- **Initial capital (100 €…2500 €):** for the plain strategy it does not change the percentage for ranges ≥ ±5 %. "
      "The filtered variants make ~284 enter/exit transactions a year, so the fixed gas weighs on small accounts: at ±15 % variant D gives "
      "−8.6 % with 100 € but −2.7 % with 2500 € (section 3). Below ~500 € the extra transactions eat a good part of the benefit.")
    A("- **Narrow ranges (±0.5…±2 %) are the worst bet**; wider ones lose less. The 1-minute data show no sweet spot in the narrow zone.")
    A("- **Profitability depends on pool volume more than on any setting:** break-even is ≈ 20 M$/day for always-LP and slightly lower (≈ 17-18 M$/day) with the filters; the pool averaged 13.6 M$/day (section 5).\n")

    # ---- table 1: ranges x variants (reference capital)
    for setting, title in (("relaxed", "relaxed limits (cooldown 5 min, ≤50/day, TWAP 5 min) — most favourable for narrow ranges"),
                           ("defaults", "contract defaults (cooldown 6 h, ≤3/day, TWAP 1 h)")):
        A(f"## 2{'a' if setting=='relaxed' else 'b'}. Result by range and strategy variant — {title}\n")
        A(f"Capital {REF} €, full year, % vs HODL.\n")
        rows = []
        for rg in RANGES:
            rows.append([R(rg)] + [f"{pct(by[(rg, setting, v)]['year'][str(REF)]):+.1f}" for v in VARIANTS])
        A(md(["range"] + list(VARIANTS), rows))

    # ---- table 3: capital x range for best variant D (relaxed)
    A("## 3. Effect of initial capital — variant D (filter + closed 13-17 UTC), relaxed limits\n")
    A("Cells: result vs HODL, % (and € P&L vs HODL for the year).\n")
    rows = []
    for rg in RANGES:
        rec = by[(rg, "relaxed", "D. Filter + closed 13-17 UTC")]["year"]
        rows.append([R(rg)] + [f"{pct(rec[str(c)]):+.1f} % ({eur(rec[str(c)]):+.0f} €)" for c in CAPS])
    A(md(["range"] + [f"{c} €" for c in CAPS], rows))
    A("Same table for the plain strategy (variant A, always LP), % only:\n")
    rows = [[R(rg)] + [f"{pct(by[(rg, 'relaxed', 'A. Always LP')]['year'][str(c)]):+.1f}" for c in CAPS] for rg in RANGES]
    A(md(["range"] + [f"{c} €" for c in CAPS], rows))

    # ---- table 4: robustness halves
    A("## 4. Robustness — does it hold in both halves of the year? (1000 €, relaxed)\n")
    rows = []
    for rg in RANGES:
        a = by[(rg, "relaxed", "A. Always LP")]; d = by[(rg, "relaxed", "D. Filter + closed 13-17 UTC")]
        rows.append([R(rg), f"{pct(a['h1']):+.1f}", f"{pct(a['h2']):+.1f}", f"{pct(d['h1']):+.1f}", f"{pct(d['h2']):+.1f}",
                     "yes" if pct(d["h1"]) > pct(a["h1"]) and pct(d["h2"]) > pct(a["h2"]) else "no", d["year"][str(REF)]["chg"]])
    A(md(["range", "A: H1", "A: H2", "D: H1", "D: H2", "D beats A in both halves", "D enter/exit events/yr"], rows))
    both = sum(1 for rg in RANGES for s in SETTINGS for v in ("B. LP closed 13-17 UTC", "C. Volatility filter", "D. Filter + closed 13-17 UTC")
               if pct(by[(rg, s, v)]["h1"]) > pct(by[(rg, s, "A. Always LP")]["h1"]) and pct(by[(rg, s, v)]["h2"]) > pct(by[(rg, s, "A. Always LP")]["h2"]))
    tot = len(RANGES) * len(SETTINGS) * 3
    A(f"\nAcross all ranges and both settings, the three 'stay out' variants beat plain always-LP in **both halves in {both} of {tot}** cases.\n")

    # ---- table 5: volume
    A("## 5. Sensitivity to pool volume — 1000 €, relaxed, selected ranges, full year\n")
    vg = (7, 13.6, 21, 30, 50)
    rows = []
    for rg in (0.02, 0.05, 0.10, 0.15):
        for v in ("A. Always LP", "D. Filter + closed 13-17 UTC"):
            rec = by[(rg, "relaxed", v)]["year"][str(REF)]
            be = (rec["hodl"] - rec["nof"]) / rec["fpm"]
            rows.append([R(rg), v] + [f"{pct(rec, x*1e6):+.0f}" for x in vg] + [f"{be:.0f}"])
    A(md(["range", "variant"] + [f"{x} M$/day" for x in vg] + ["break-even M$/day"], rows))
    A("_Linear in volume at constant active liquidity; high-volume columns are upper bounds (more LPs would dilute fees)._\n")

    # ---- recommendations
    A("## 6. What this means\n")
    A("1. **Do not expect to beat holding with the current setup.** Treat any live test (e.g. 100-500 €) as validation of the machinery, not as an investment.")
    A("2. **Prefer wide ranges (±10…±15 %) and few rebalances** unless pool volume is persistently above ~20 M$/day; use the measured weekly volume (`python3 backtest/pool_volume.py 168`) as the go/no-go signal.")
    A("3. **If the strategy is automated further, staying out at set hours (US open) and in high volatility is the lever with the best, most consistent evidence** (sections 2 and 4) — implementation in the contract is in progress and needs your sign-off because it changes the strategy.")
    A("4. **Still open:** a gas-price gate (no historical gas data available), more than one year of history, and own-liquidity price impact.\n")
    A("_Caveats: one bear-market year · Binance prices as a proxy for pool prices · constant active liquidity · no MEV/JIT · gas assumed 0.02 $/tx._")
    (HERE / "EXECUTIVE_SUMMARY.md").write_text("\n".join(out) + "\n")
    print("wrote backtest/EXECUTIVE_SUMMARY.md")


if __name__ == "__main__":
    main()
